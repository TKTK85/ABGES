"""Resolve complete Windows/Python 3.14 dependency closures, preserving existing pins.

Run with the target interpreter. pip resolves but does not install packages.
Review lock changes and verify with pip install --require-hashes afterward.
"""
import json
from pathlib import Path
import re
import subprocess
import sys
import tempfile


def main():
    if sys.platform != 'win32' or sys.version_info[:2] != (3, 14):
        raise SystemExit('Locks target Windows and CPython 3.14 only')
    root = Path(__file__).resolve().parents[1]
    resolved = {}
    with tempfile.TemporaryDirectory() as work:
        work = Path(work)
        for name in ('requirements', 'requirements-dev'):
            lock = root / (name + '.lock')
            pins = re.findall(r'^([A-Za-z0-9_.-]+==[^\s\\]+)', lock.read_text(encoding='utf-8'), re.M) if lock.exists() else []
            constraint, report = work / 'constraints.txt', work / 'report.json'
            constraint.write_text('\n'.join(pins), encoding='utf-8')
            subprocess.run([sys.executable, '-m', 'pip', 'install', '--dry-run', '--ignore-installed',
                            '--report', str(report), '-r', str(root / (name + '.txt')),
                            '-c', str(constraint)], check=True, cwd=root)
            packages = json.loads(report.read_text(encoding='utf-8'))['install']
            lines = ['# Generated by scripts/refresh_dependency_locks.py',
                     '# Target: Windows x64 / CPython 3.14. Install with --require-hashes.', '']
            for item in sorted(packages, key=lambda p: p['metadata']['name'].lower()):
                digest = item['download_info']['archive_info']['hashes']['sha256']
                lines += [item['metadata']['name'] + '==' + item['metadata']['version'] + ' \\',
                          '    --hash=sha256:' + digest, '']
            resolved[lock] = '\n'.join(lines)
        # Publish only when both closures resolved successfully.
        for lock, content in resolved.items():
            lock.write_text(content, encoding='utf-8')


if __name__ == '__main__':
    main()
